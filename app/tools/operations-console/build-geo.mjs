// One-off: builds public/geo.js (pre-projected US outline, AlbersUSA layout at 975×610) from a local world TopoJSON.
// geo.js is built from countries-50m.json in world-atlas 2.0.2 (https://github.com/topojson/world-atlas, ISC), made from
// Natural Earth (public domain); that file rebuilds it byte for byte.
// Usage: node app/tools/build-geo.mjs <path/to/worldTopoJSON.json>
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { APP_URL } from '../../public/source-layout.js';
export const GEO_OUTPUT = fileURLToPath(new URL('public/operations-console/geo.js', APP_URL));
export async function main({ output = GEO_OUTPUT } = {}) {


const src = process.argv[2];
if (!src) { console.error('usage: node app/tools/build-geo.mjs <worldTopoJSON.json>'); process.exit(1); }
const topo = JSON.parse(await readFile(src, 'utf8'));

// Decode quantized, delta-encoded arcs.
const [sx, sy] = topo.transform?.scale || [1, 1], [dx, dy] = topo.transform?.translate || [0, 0];
const arcs = topo.arcs.map((a) => { let x = 0, y = 0; return a.map(([px, py]) => (topo.transform ? [(x += px) * sx + dx, (y += py) * sy + dy] : [px, py])); });
const ring = (ids) => ids.flatMap((i, n) => { const a = i < 0 ? [...arcs[~i]].reverse() : arcs[i]; return n ? a.slice(1) : a; });

const usa = Object.values(topo.objects)[0].geometries.find((g) => g.id === '840' || g.properties?.name === 'United States' || g.properties?.name === 'United States of America');
if (!usa) throw new Error('USA (id 840) not found');
const polys = usa.type === 'Polygon' ? [usa.arcs] : usa.arcs;

// Conic equal-area, same constants as d3.geoAlbersUsa at scale 1300 / translate [487.5, 305].
function conic(p0, p1, rot, center, k, tx, ty) {
  const rad = Math.PI / 180, s0 = Math.sin(p0 * rad), n = (s0 + Math.sin(p1 * rad)) / 2, c = 1 + s0 * (2 * n - s0), r0 = Math.sqrt(c) / n;
  const raw = (l, p) => { const r = Math.sqrt(c - 2 * n * Math.sin(p)) / n; return [r * Math.sin(l * n), r0 - r * Math.cos(l * n)]; };
  const cc = raw(center[0] * rad, center[1] * rad);
  return (lon, lat) => { let l = lon + rot; if (l > 180) l -= 360; if (l < -180) l += 360; const q = raw(l * rad, lat * rad); return [tx + k * (q[0] - cc[0]), ty - k * (q[1] - cc[1])]; };
}
const K = 1300, TX = 487.5, TY = 305;
const lower48 = conic(29.5, 45.5, 96, [-0.6, 38.7], K, TX, TY);
const alaska = conic(55, 65, 154, [-2, 58.5], 0.35 * K, TX - 0.307 * K, TY + 0.201 * K);
const hawaii = conic(8, 18, 157, [-3, 19.9], K, TX - 0.205 * K, TY + 0.212 * K);
const which = ([lon, lat]) => (lat > 51 && lon < -129 ? 'ak' : lat < 23 && lon < -150 ? 'hi' : lat > 24 && lat < 50 && lon > -126 ? 'l48' : null);
const PROJ = { l48: lower48, ak: alaska, hi: hawaii };

const out = { l48: [], ak: [], hi: [] };
for (const poly of polys) {
  const outer = ring(poly[0]);
  const region = which(outer[Math.floor(outer.length / 2)]) || which(outer[0]);
  if (!region) continue;
  const d = poly.map((r) => { const pts = ring(r).map(([lon, lat]) => PROJ[region](lon, lat)); return 'M' + pts.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join('L') + 'Z'; }).join('');
  out[region].push(d);
}
const js = `// Generated by app/tools/build-geo.mjs — US outline pre-projected to AlbersUSA (975×610). Do not edit.\nwindow.US_GEO = ${JSON.stringify({ l48: out.l48.join(''), ak: out.ak.join(''), hi: out.hi.join('') })};\n`;
const dest = output;
await writeFile(dest, js);
console.log(`wrote ${dest} (${(js.length / 1024).toFixed(1)} KB; polygons l48=${out.l48.length} ak=${out.ak.length} hi=${out.hi.length})`);

}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
